#!/usr/bin/env node
// Builds a real end-to-end fixture for the gate contract tests:
//   - a tree with 3 credentials (ours at index 2, so the path has 0/1 bits),
//   - a Groth16 proof for an investor with a deterministic Stellar address,
//   - writes build/fixture.json and contracts/contracts/gate/src/fixtures/residence.rs
//     (hex consts consumed by the Rust tests).
// Also checks off-chain that the proof verifies and that a US credential
// cannot produce a witness.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import * as snarkjs from "snarkjs";
import { Keypair } from "@stellar/stellar-sdk";
import {
  IncrementalTree,
  credentialLeaf,
  frToHex,
  getPoseidon,
  vkToSoroban,
} from "./lib.mjs";
import { proveResidence } from "./prove.mjs";

const here = (p) => new URL(p, import.meta.url).pathname;
const RUST_OUT = here("../../contracts/contracts/gate/src/fixtures/residence.rs");

const NOW = 1761400000n; // 2025-10-25T13:46:40Z, the ledger timestamp used in tests
const ONE_YEAR = 365n * 24n * 3600n;
const investor = Keypair.fromRawEd25519Seed(Buffer.alloc(32, 7)).publicKey();

const cred = {
  country: 276n, // Germany
  expiry: NOW + ONE_YEAR,
  secret: 0x1234567890abcdef1234567890abcdef1234567890abcdefn,
};
const scope = 1n; // platform-wide scope

const tree = await IncrementalTree.create();
const otherLeaves = [
  await credentialLeaf(250n, NOW + ONE_YEAR, 111n), // France
  await credentialLeaf(392n, NOW + ONE_YEAR, 222n), // Japan
];
const rootsAfter = [];
for (const l of otherLeaves) {
  tree.insert(l);
  rootsAfter.push(tree.root());
}
const myLeaf = await credentialLeaf(cred.country, cred.expiry, cred.secret);
const myIndex = tree.insert(myLeaf);
rootsAfter.push(tree.root());
const { path_elements, path_indices } = tree.path(myIndex);

const out = await proveResidence({
  ...cred,
  path_elements,
  path_indices,
  root: tree.root(),
  now: NOW,
  scope,
  address: investor,
});

const vkJson = JSON.parse(readFileSync(here("../build/verification_key.json"), "utf8"));
if (!(await snarkjs.groth16.verify(vkJson, out.publicSignals, out.proof))) {
  throw new Error("snarkjs failed to verify its own proof");
}
console.log("off-chain verification: OK");

// A US resident must not be able to build a witness.
try {
  const usLeaf = await credentialLeaf(840n, cred.expiry, 999n);
  const t2 = await IncrementalTree.create();
  t2.insert(usLeaf);
  await proveResidence({ country: 840n, expiry: cred.expiry, secret: 999n, ...t2.path(0),
    root: t2.root(), now: NOW, scope, address: investor });
  throw new Error("US credential produced a proof!");
} catch (e) {
  if (String(e.message).includes("US credential produced")) throw e;
  console.log("US credential rejected by circuit: OK");
}

// Expired credential must fail too.
try {
  const l = await credentialLeaf(276n, NOW - 1n, 5n);
  const t3 = await IncrementalTree.create();
  t3.insert(l);
  await proveResidence({ country: 276n, expiry: NOW - 1n, secret: 5n, ...t3.path(0),
    root: t3.root(), now: NOW, scope, address: investor });
  throw new Error("expired credential produced a proof!");
} catch (e) {
  if (String(e.message).includes("produced a proof")) throw e;
  console.log("expired credential rejected by circuit: OK");
}

const H = await getPoseidon();
const vk = vkToSoroban(vkJson);
const fixture = {
  investor,
  now: NOW.toString(),
  scope: scope.toString(),
  leaves: [...otherLeaves, myLeaf].map(String),
  roots_after: rootsAfter.map(String),
  empty_root: tree.zeros[tree.depth].toString(),
  poseidon_1_2: H([1n, 2n]).toString(),
  vk,
  proof: out.proof,
  public_signals: out.publicSignals,
  soroban: out.soroban,
};
writeFileSync(here("../build/fixture.json"), JSON.stringify(fixture, null, 2));

const s = (x) => `"${x}"`;
const hexArr = (xs) => `&[\n${xs.map((x) => `    "${x}",`).join("\n")}\n]`;
const rust = `// @generated by circuits/scripts/make-fixture.mjs -- do not edit.
// Real snarkjs Groth16 proof (BN254) for circuits/residence.circom.
// Hex is big-endian. G1 = x||y (64B); G2 = x.c1||x.c0||y.c1||y.c0 (128B).
#![allow(dead_code)]

pub const VK_ALPHA: &str = ${s(vk.alpha)};
pub const VK_BETA: &str = ${s(vk.beta)};
pub const VK_GAMMA: &str = ${s(vk.gamma)};
pub const VK_DELTA: &str = ${s(vk.delta)};
pub const VK_IC: &[&str] = ${hexArr(vk.ic)};

pub const PROOF_A: &str = ${s(out.soroban.proof.a)};
pub const PROOF_B: &str = ${s(out.soroban.proof.b)};
pub const PROOF_C: &str = ${s(out.soroban.proof.c)};

pub const INVESTOR: &str = ${s(investor)};
pub const NOW: u64 = ${NOW};
pub const ROOT: &str = ${s(out.hex.root)};
pub const NULLIFIER: &str = ${s(out.hex.nullifier)};
pub const SCOPE: &str = ${s(out.hex.scope)};
pub const ADDRESS_HASH: &str = ${s(out.hex.address_hash)};

/// Leaves in insertion order (the proof is for the last one).
pub const LEAVES: &[&str] = ${hexArr(fixture.leaves.map(frToHex))};
/// Root computed in JS (circomlibjs) after each insertion.
pub const ROOTS_AFTER: &[&str] = ${hexArr(rootsAfter.map(frToHex))};
pub const EMPTY_ROOT: &str = ${s(frToHex(fixture.empty_root))};
/// circomlibjs Poseidon([1, 2])
pub const POSEIDON_1_2: &str = ${s(frToHex(fixture.poseidon_1_2))};
`;
mkdirSync(here("../../contracts/contracts/gate/src/fixtures"), { recursive: true });
writeFileSync(RUST_OUT, rust);
console.log("wrote build/fixture.json and", RUST_OUT);
console.log("public signals:", out.publicSignals);
process.exit(0);
